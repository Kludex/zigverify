//! The ways a proof can fail, shared by the harness side that reports them and the
//! runner that prints them.

pub const Kind = enum(u32) {
    assert,
    panic,
    sentinel_mismatch,
    unwrap_error,
    out_of_bounds,
    start_greater_than_end,
    inactive_union_field,
    slice_cast_len_remainder,
    reached_unreachable,
    unwrap_null,
    cast_to_null,
    incorrect_alignment,
    invalid_error_code,
    integer_out_of_bounds,
    integer_overflow,
    shl_overflow,
    shr_overflow,
    divide_by_zero,
    exact_division_remainder,
    integer_part_out_of_bounds,
    corrupt_switch,
    shift_rhs_too_big,
    invalid_enum_value,
    for_len_mismatch,
    copy_len_mismatch,
    memcpy_alias,
    noreturn_returned,
    invalid_free,
    leak,

    /// A sentence for the report. `{a}` and `{b}` stand for the two operands the check carries.
    pub fn describe(kind: Kind) []const u8 {
        return switch (kind) {
            .assert => "verifier.assert failed",
            .panic => "@panic reached",
            .sentinel_mismatch => "sentinel mismatch",
            .unwrap_error => "attempt to unwrap error",
            .out_of_bounds => "index out of bounds: index {a}, len {b}",
            .start_greater_than_end => "start index {a} is larger than end index {b}",
            .inactive_union_field => "access of inactive union field",
            .slice_cast_len_remainder => "slice length {a} does not divide exactly into destination elements",
            .reached_unreachable => "reached unreachable code",
            .unwrap_null => "attempt to use null value",
            .cast_to_null => "cast causes pointer to be null",
            .incorrect_alignment => "incorrect alignment",
            .invalid_error_code => "invalid error code",
            .integer_out_of_bounds => "integer does not fit in destination type",
            .integer_overflow => "integer overflow",
            .shl_overflow => "left shift overflowed bits",
            .shr_overflow => "right shift overflowed bits",
            .divide_by_zero => "division by zero",
            .exact_division_remainder => "exact division produced remainder",
            .integer_part_out_of_bounds => "integer part of floating point value out of bounds",
            .corrupt_switch => "switch on corrupt value",
            .shift_rhs_too_big => "shift amount is greater than the type size",
            .invalid_enum_value => "invalid enum value",
            .for_len_mismatch => "for loop over objects with non-equal lengths",
            .copy_len_mismatch => "source and destination arguments have non-equal lengths",
            .memcpy_alias => "@memcpy arguments alias",
            .noreturn_returned => "'noreturn' function returned",
            .invalid_free => "free of memory that is not live: a double free, or a pointer the allocator never returned",
            .leak => "an allocation is still live at the end: a leak",
        };
    }
};
